"""Shared SQLite connection configuration."""

import sqlite3
import json
import math
from contextlib import closing
from pathlib import Path


DATABASE_PATH = Path(__file__).resolve().parent.parent / "math_ai.db"


def get_connection(database_path: str | Path = DATABASE_PATH, *, read_only: bool = False) -> sqlite3.Connection:
    """Open a connection with named rows and enforced foreign keys.

    The caller owns the connection and must close it after use.
    An alternative path allows tests to use isolated temporary databases.
    """
    if read_only:
        connection = sqlite3.connect(Path(database_path).resolve().as_uri() + "?mode=ro", uri=True)
    else:
        connection = sqlite3.connect(database_path)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def get_training_questions(database_path: str | Path = DATABASE_PATH) -> list[dict]:
    """Read function-topic questions, join knowledge names, and validate options."""
    if not Path(database_path).is_file():
        raise FileNotFoundError("数据库不存在，请先运行 python init_db.py。")
    with closing(get_connection(database_path)) as connection:
        rows = connection.execute(
            """SELECT q.*, k.name AS knowledge_point_name
               FROM questions AS q
               JOIN knowledge_points AS k ON k.id = q.knowledge_point_id
               WHERE k.topic = ? AND q.question_type = ? ORDER BY q.id""",
            ("函数", "single_choice"),
        ).fetchall()
    questions = []
    for row in rows:
        question = dict(row)
        try:
            options = json.loads(question["options"])
        except (json.JSONDecodeError, TypeError) as error:
            raise ValueError(f"题目 {question['id']} 的选项 JSON 无效。") from error
        if (not isinstance(options, dict) or set(options) != {"A", "B", "C", "D"}
                or any(not isinstance(value, str) or not value.strip() for value in options.values())
                or question["answer"] not in options):
            raise ValueError(f"题目 {question['id']} 的选项或答案无效。")
        question["options"] = options
        questions.append(question)
    return questions


def record_attempt(
    student_id: str, question_id: str, user_answer: str, is_correct: int,
    answer_time: float, hint_count: int = 0, retry_count: int = 0,
    error_type: str | None = None, *, database_path: str | Path = DATABASE_PATH,
) -> int:
    """Commit one attempt and return its ID; timestamp is generated by SQLite."""
    if is_correct not in (0, 1):
        raise ValueError("is_correct must be 0 or 1")
    if not math.isfinite(answer_time) or answer_time < 0:
        raise ValueError("answer_time must be finite and nonnegative")
    with closing(get_connection(database_path)) as connection:
        with connection:
            cursor = connection.execute(
                """INSERT INTO attempts
                   (student_id, question_id, user_answer, is_correct, answer_time,
                    hint_count, retry_count, error_type)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (student_id, question_id, user_answer, is_correct, float(answer_time),
                 hint_count, retry_count, error_type),
            )
            attempt_id = cursor.lastrowid
    return attempt_id


def get_recent_attempts(
    student_id: str, limit: int = 10, *, database_path: str | Path = DATABASE_PATH,
) -> list[sqlite3.Row]:
    """Return a student's newest attempts, with ID breaking timestamp ties."""
    if not isinstance(limit, int) or isinstance(limit, bool) or limit < 0:
        raise ValueError("limit must be a nonnegative integer")
    with closing(get_connection(database_path)) as connection:
        return connection.execute(
            """SELECT * FROM attempts WHERE student_id = ?
               ORDER BY created_at DESC, id DESC LIMIT ?""",
            (student_id, limit),
        ).fetchall()


def get_knowledge_point(
    knowledge_point_id: str, *, database_path: str | Path = DATABASE_PATH,
) -> sqlite3.Row | None:
    """Read knowledge metadata without creating or modifying a database."""
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            "SELECT * FROM knowledge_points WHERE id = ?", (knowledge_point_id,),
        ).fetchone()


def get_function_knowledge_points(
    *, database_path: str | Path = DATABASE_PATH,
) -> list[sqlite3.Row]:
    """Return the five MVP knowledge points in ID order, including untrained ones."""
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            """SELECT * FROM knowledge_points
               WHERE id IN (?, ?, ?, ?, ?) ORDER BY id""",
            ("K001", "K002", "K003", "K004", "K005"),
        ).fetchall()


def get_knowledge_attempts(
    student_id: str, knowledge_point_id: str, *, database_path: str | Path = DATABASE_PATH,
) -> list[sqlite3.Row]:
    """Read all matching attempts with difficulty, newest first and deterministic ties."""
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            """SELECT a.id, a.is_correct, q.difficulty, a.created_at, a.question_id
               FROM attempts AS a JOIN questions AS q ON q.id = a.question_id
               WHERE a.student_id = ? AND q.knowledge_point_id = ?
               ORDER BY a.created_at DESC, a.id DESC""",
            (student_id, knowledge_point_id),
        ).fetchall()
