"""Shared SQLite connection configuration."""

import sqlite3
import json
import math
from contextlib import closing
from pathlib import Path
from settings import get_database_path, get_active_taxonomy_version


DATABASE_PATH = Path(__file__).resolve().parent.parent / "math_ai.db"


def get_connection(database_path: str | Path | None = None, *, read_only: bool = False) -> sqlite3.Connection:
    """Open a connection with named rows and enforced foreign keys.

    The caller owns the connection and must close it after use.
    An alternative path allows tests to use isolated temporary databases.
    """
    database_path = get_database_path() if database_path is None else Path(database_path)
    if read_only:
        connection = sqlite3.connect(Path(database_path).resolve().as_uri() + "?mode=ro", uri=True)
    else:
        connection = sqlite3.connect(database_path)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


def get_training_questions(database_path: str | Path | None = None, *, taxonomy_version: str | None = None) -> list[dict]:
    """Read function-topic questions, join knowledge names, and validate options."""
    database_path = get_database_path() if database_path is None else Path(database_path)
    if not Path(database_path).is_file():
        raise FileNotFoundError("数据库不存在，请先运行 python init_db.py。")
    if _version(taxonomy_version) == 'function_v2':
        return get_approved_questions(database_path=database_path, taxonomy_version='function_v2')
    with closing(get_connection(database_path, read_only=True)) as connection:
        rows = connection.execute(
            """SELECT q.*, k.name AS knowledge_point_name
               FROM questions AS q
               JOIN knowledge_points AS k ON k.id = q.knowledge_point_id
               WHERE k.topic = ? AND q.question_type = ? ORDER BY q.id""",
            ("函数", "single_choice"),
        ).fetchall()
    questions = []
    for row in rows:
        question = dict(row)
        try:
            options = json.loads(question["options"])
        except (json.JSONDecodeError, TypeError) as error:
            raise ValueError(f"题目 {question['id']} 的选项 JSON 无效。") from error
        if (not isinstance(options, dict) or set(options) != {"A", "B", "C", "D"}
                or any(not isinstance(value, str) or not value.strip() for value in options.values())
                or question["answer"] not in options):
            raise ValueError(f"题目 {question['id']} 的选项或答案无效。")
        question["options"] = options
        questions.append(question)
    return questions


def record_attempt(
    student_id: str, question_id: str, user_answer: str, is_correct: int,
    answer_time: float, hint_count: int = 0, retry_count: int = 0,
    error_type: str | None = None, *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> int:
    """Commit one attempt and return its ID; timestamp is generated by SQLite."""
    if is_correct not in (0, 1):
        raise ValueError("is_correct must be 0 or 1")
    if not math.isfinite(answer_time) or answer_time < 0:
        raise ValueError("answer_time must be finite and nonnegative")
    with closing(get_connection(database_path)) as connection:
        with connection:
            if _version(taxonomy_version)=='function_v2' and not connection.execute(
                "SELECT 1 FROM question_knowledge_mappings WHERE taxonomy_version=? AND question_id=? AND role=? AND review_status=?",
                ('function_v2',question_id,'primary','approved')).fetchone():
                raise ValueError('未批准题不能提交。')
            cursor = connection.execute(
                """INSERT INTO attempts
                   (student_id, question_id, user_answer, is_correct, answer_time,
                    hint_count, retry_count, error_type)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (student_id, question_id, user_answer, is_correct, float(answer_time),
                 hint_count, retry_count, error_type),
            )
            attempt_id = cursor.lastrowid
    return attempt_id


def get_recent_attempts(
    student_id: str, limit: int = 10, *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> list[sqlite3.Row]:
    """Return a student's newest attempts, with ID breaking timestamp ties."""
    if not isinstance(limit, int) or isinstance(limit, bool) or limit < 0:
        raise ValueError("limit must be a nonnegative integer")
    with closing(get_connection(database_path, read_only=True)) as connection:
        if _version(taxonomy_version)=='function_v2':
            return connection.execute('''SELECT a.* FROM attempts a JOIN question_knowledge_mappings m ON m.question_id=a.question_id
                WHERE a.student_id=? AND m.taxonomy_version=? AND m.role=? AND m.review_status=?
                ORDER BY a.created_at DESC,a.id DESC LIMIT ?''',(student_id,'function_v2','primary','approved',limit)).fetchall()
        return connection.execute(
            """SELECT * FROM attempts WHERE student_id = ?
               ORDER BY created_at DESC, id DESC LIMIT ?""",
            (student_id, limit),
        ).fetchall()


def get_knowledge_point(
    knowledge_point_id: str, *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> sqlite3.Row | None:
    """Read knowledge metadata without creating or modifying a database."""
    if _version(taxonomy_version) == 'function_v2':
        return next((p for p in get_knowledge_points('function_v2', database_path=database_path) if p['id']==knowledge_point_id),None)
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            "SELECT * FROM knowledge_points WHERE id = ?", (knowledge_point_id,),
        ).fetchone()


def get_function_knowledge_points(
    *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> list[sqlite3.Row]:
    """Return every point in the requested version, including untrained ones."""
    if _version(taxonomy_version) == 'function_v2':
        return get_knowledge_points('function_v2', database_path=database_path)
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            """SELECT * FROM knowledge_points
               WHERE topic = ? ORDER BY id""",
            ("函数",),
        ).fetchall()


def get_knowledge_attempts(
    student_id: str, knowledge_point_id: str, *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> list[sqlite3.Row]:
    """Read all matching attempts with difficulty, newest first and deterministic ties."""
    if _version(taxonomy_version) == 'function_v2':
        with closing(get_connection(database_path, read_only=True)) as connection:
            return connection.execute('''SELECT a.id,a.is_correct,q.difficulty,a.created_at,a.question_id
                FROM attempts a JOIN questions q ON q.id=a.question_id
                JOIN question_knowledge_mappings m ON m.question_id=q.id
                WHERE a.student_id=? AND m.taxonomy_version=? AND m.knowledge_point_id=?
                AND m.role=? AND m.review_status=? ORDER BY a.created_at DESC,a.id DESC''',
                (student_id,'function_v2',knowledge_point_id,'primary','approved')).fetchall()
    with closing(get_connection(database_path, read_only=True)) as connection:
        return connection.execute(
            """SELECT a.id, a.is_correct, q.difficulty, a.created_at, a.question_id
               FROM attempts AS a JOIN questions AS q ON q.id = a.question_id
               WHERE a.student_id = ? AND q.knowledge_point_id = ?
               ORDER BY a.created_at DESC, a.id DESC""",
            (student_id, knowledge_point_id),
        ).fetchall()


def get_questions_for_knowledge(
    knowledge_point_id: str, *, database_path: str | Path | None = None, taxonomy_version: str | None = None,
) -> list[dict]:
    """Read practice previews without exposing correct answers or solutions."""
    if _version(taxonomy_version) == 'function_v2':
        fields=('id','stem','difficulty','knowledge_point_id','knowledge_point_name')
        return [{key:q[key] for key in fields} for q in get_approved_questions(knowledge_point_id, database_path=database_path,taxonomy_version='function_v2')]
    with closing(get_connection(database_path, read_only=True)) as connection:
        rows = connection.execute(
            """SELECT q.id, q.stem, q.difficulty, q.knowledge_point_id,
                      k.name AS knowledge_point_name
               FROM questions AS q JOIN knowledge_points AS k ON k.id = q.knowledge_point_id
               WHERE q.knowledge_point_id = ? AND q.question_type = ? ORDER BY q.id""",
            (knowledge_point_id, "single_choice"),
        ).fetchall()
    return [dict(row) for row in rows]


def _version(version=None):
    version=version or get_active_taxonomy_version()
    if version not in ('function_v1','function_v2'): raise ValueError('知识体系版本无效。')
    return version


def get_knowledge_points(taxonomy_version=None, *, database_path=None):
    version=_version(taxonomy_version)
    if version=='function_v1':
        return get_function_knowledge_points(database_path=database_path,taxonomy_version=version)
    with closing(get_connection(database_path,read_only=True)) as c:
        points=[dict(r) for r in c.execute('SELECT * FROM knowledge_catalog WHERE taxonomy_version=? AND topic=? ORDER BY display_order,id',(version,'函数'))]
        for p in points:
            p['prerequisite_ids']=json.dumps([r[0] for r in c.execute('SELECT prerequisite_id FROM knowledge_prerequisites WHERE taxonomy_version=? AND knowledge_point_id=? ORDER BY prerequisite_id',(version,p['id']))])
        return points


def get_question_mapping(question_id, taxonomy_version=None, *, database_path=None):
    with closing(get_connection(database_path,read_only=True)) as c:
        return [dict(r) for r in c.execute('SELECT * FROM question_knowledge_mappings WHERE taxonomy_version=? AND question_id=? ORDER BY role,knowledge_point_id',(_version(taxonomy_version),question_id))]


def get_question_prerequisites(question_id, taxonomy_version=None, *, database_path=None):
    if _version(taxonomy_version)=='function_v1': return []
    with closing(get_connection(database_path,read_only=True)) as c:
        return [r[0] for r in c.execute('SELECT knowledge_point_id FROM question_prerequisites WHERE taxonomy_version=? AND question_id=? ORDER BY knowledge_point_id',(_version(taxonomy_version),question_id))]


def get_approved_questions(knowledge_point_id=None, *, database_path=None, taxonomy_version=None):
    version=_version(taxonomy_version)
    if version=='function_v1':
        rows=get_training_questions(database_path,taxonomy_version=version)
        return [q for q in rows if knowledge_point_id is None or q['knowledge_point_id']==knowledge_point_id]
    with closing(get_connection(database_path,read_only=True)) as c:
        rows=c.execute('''SELECT q.id,q.stem,q.options,q.answer,q.explanation,q.difficulty,q.estimated_time,
            m.knowledge_point_id,k.name AS knowledge_point_name FROM questions q
            JOIN question_knowledge_mappings m ON q.id=m.question_id
            JOIN knowledge_catalog k ON k.taxonomy_version=m.taxonomy_version AND k.id=m.knowledge_point_id
            WHERE m.taxonomy_version=? AND m.role=? AND m.review_status=? AND q.question_type=?
            AND (? IS NULL OR m.knowledge_point_id=?) ORDER BY q.id''',
            (version,'primary','approved','single_choice',knowledge_point_id,knowledge_point_id)).fetchall()
    return [{**dict(r),'options':json.loads(r['options'])} for r in rows]
